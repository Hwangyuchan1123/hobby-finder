drop table if exists public.hobbies;

create table public.hobbies (
  id              bigint generated by default as identity primary key,
  name            text        not null,
  emoji           text        not null default '✨',
  category        text        not null,
  description     text        not null,
  -- ① 활동 장소
  location        text        not null check (location in ('indoor', 'outdoor', 'both')),
  -- ② 에너지 방향
  social          text        not null check (social in ('solo', 'group', 'both')),
  -- ③ 예산 수준
  budget          text        not null check (budget in ('low', 'high')),
  -- ④ 선호 스타일
  style           text        not null check (style in ('active', 'creative')),
  -- ⑤ 시간 투자
  time_commitment text        not null check (time_commitment in ('short', 'long')),
  -- ⑥ 보상/성취 방식: 결과물 / 힐링 / 성장
  reward          text        not null check (reward in ('output', 'healing', 'growth')),
  -- ⑦ 입문 장벽: 바로 시작 / 장비 갖추고 시작
  entry_barrier   text        not null check (entry_barrier in ('instant', 'gear')),
  -- ⑧ 분위기: 차분·감성 / 역동·트렌디
  mood            text        not null check (mood in ('calm', 'dynamic')),
  monthly_cost    text        not null,
  difficulty      smallint    not null check (difficulty between 1 and 5),
  tags            text[]      not null default '{}',
  starter_tip     text        not null,
  created_at      timestamptz not null default now()
);

comment on table public.hobbies is '맞춤형 취미 추천용 취미 마스터 데이터';

